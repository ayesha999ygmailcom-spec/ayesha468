"""# Data Loading and Basic Inspection
Let's load the `starbucks.csv` file into a Pandas DataFrame and check its dimensions, columns, data types, and any missing values.
"""

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# Load the dataset
df = pd.read_csv('/content/extracted_data/starbucks.csv')

# Display basic details
print("Dataset Shape:", df.shape)
print("\n--- Dataset Columns & Types ---")
df.info()

print("\n--- First 5 Rows ---")
display(df.head())

print("\n--- Missing Values Summary ---")
print(df.isnull().sum())



"""# Exploratory Data Analysis & Visualizations
Let's generate statistical summaries and plots to better understand the distributions of numerical columns and any relationships within the data.
"""

# Clean column names by stripping leading/trailing whitespaces
df.columns = df.columns.str.strip()

# Statistical summary of numeric columns
print("\n--- Descriptive Statistics ---")
display(df.describe(include='all'))

# Visualizing distributions of key numerical attributes if present
numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()
if len(numeric_cols) > 0:
    plt.figure(figsize=(12, 8))
    for i, col in enumerate(numeric_cols[:6], 1):
        plt.subplot(2, 3, i)
        sns.histplot(df[col].dropna(), kde=True, bins=20)
        plt.title(f'Distribution of {col}')
    plt.tight_layout()
    plt.show()
else:
    print("No numerical columns found for distribution plots.")

"""# Model Preparation: Train-Test Split & Decision Tree
Now we will prepare the dataset for predictive modeling. We will split the dataset into 80% training and 20% testing data, fit a Decision Tree, and evaluate its performance.
"""

from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier, DecisionTreeRegressor
from sklearn.metrics import classification_report, accuracy_score, mean_squared_error, r2_score
from sklearn.preprocessing import LabelEncoder

# Prepare copy of dataframe
model_df = df.copy()

# Automatically identify categorical columns and encode them
label_encoders = {}
for col in model_df.select_dtypes(include=['object']).columns:
    le = LabelEncoder()
    model_df[col] = le.fit_transform(model_df[col].astype(str))
    label_encoders[col] = le

# Let's dynamically select the target column. We'll check if a common column like 'Calories' exists to predict, or use the last numeric column.
if 'Calories' in df.columns:
    target_col = 'Calories'
elif len(numeric_cols) > 0:
    target_col = numeric_cols[-1]
else:
    target_col = model_df.columns[-1]

print(f"Selected target column for modeling: {target_col}")

X = model_df.drop(columns=[target_col])
y = model_df[target_col]

# Train-test split (80% training, 20% testing)
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.20, random_state=42)

# Initialize and fit the Decision Tree depending on whether the target is continuous or discrete
if y.nunique() > 10 and np.issubdtype(y.dtype, np.number):
    print("Running Decision Tree Regressor...")
    model = DecisionTreeRegressor(random_state=42, max_depth=5)
    model.fit(X_train, y_train)
    predictions = model.predict(X_test)
    print("Mean Squared Error:", mean_squared_error(y_test, predictions))
    print("R2 Score:", r2_score(y_test, predictions))
else:
    print("Running Decision Tree Classifier...")
    model = DecisionTreeClassifier(random_state=42, max_depth=5)
    model.fit(X_train, y_train)
    predictions = model.predict(X_test)
    print("Accuracy:", accuracy_score(y_test, predictions))
    print("\nClassification Report:\n", classification_report(y_test, predictions))

"""# Model Evaluation & Post-Testing Analysis
Let's visualize the results of our Decision Tree model by plotting actual vs. predicted values and examining feature importances.
"""

# 1. Plot Actual vs. Predicted Calories
plt.figure(figsize=(14, 6))

plt.subplot(1, 2, 1)
sns.scatterplot(x=y_test, y=predictions, alpha=0.7, color='teal')
