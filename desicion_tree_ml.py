"""# Regression Performance Metrics (Accuracy & Precision equivalents)
Let's compute the Mean Absolute Error (MAE) and Root Mean Squared Error (RMSE) to quantify the prediction errors in terms of calorie units.
"""

from sklearn.metrics import mean_absolute_error

# Calculate regression equivalents of accuracy and precision
mae = mean_absolute_error(y_test, predictions)
rmse = np.sqrt(mean_squared_error(y_test, predictions))
r2 = r2_score(y_test, predictions)

print("--- Model Prediction Quality Metrics ---")
print(f"Mean Absolute Error (MAE): {mae:.2f} calories")
print(f"Root Mean Squared Error (RMSE): {rmse:.2f} calories")
print(f"R2 Score (Variance Explained): {r2 * 100:.2f}%")

"""# Visualizing Prediction Accuracy with a Pie Chart
Let's calculate the absolute errors for the test set predictions, group them into descriptive accuracy ranges, and visualize them using a pie chart.
"""

# Calculate absolute errors
absolute_errors = np.abs(y_test - predictions)

# Categorize errors
bins = [0, 10, 30, np.inf]
labels = ['Highly Accurate (Error ≤ 10 kcal)', 'Moderately Accurate (Error 10-30 kcal)', 'Lower Accuracy (Error > 30 kcal)']
error_categories = pd.cut(absolute_errors, bins=bins, labels=labels, include_lowest=True)
category_counts = error_categories.value_counts()

# Plot pie chart
plt.figure(figsize=(8, 8))
plt.pie(
    category_counts,
    labels=category_counts.index,
    autopct='%1.1f%%',
    startangle=140,
    colors=['#2ca02c', '#ff7f0e', '#d62728'],
    explode=(0.05, 0.05, 0.05)
)
plt.title('Distribution of Model Prediction Accuracy (Absolute Errors)')
plt.show()

